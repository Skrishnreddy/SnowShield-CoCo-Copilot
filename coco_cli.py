def main():
    parser = argparse.ArgumentParser(description="SnowShield CoCo CLI - Autonomous Snowflake Security Copilot")
    subparsers = parser.add_subparsers(dest="command", help="CLI commands")
    
    run_parser = subparsers.add_parser("run", help="Execute a modular CoCo skill")
    run_parser.add_argument("--skill", required=True, choices=["risk-audit-skill", "compliance-guard-skill", "auto-remediation-skill"], help="CoCo skill to invoke")
    run_parser.add_argument("prompt", type=str, help="Instruction or query prompt for the skill")
    
    list_parser = subparsers.add_parser("list-skills", help="List all registered CoCo skills")
    
    args = parser.parse_args()
    print_banner()
    
    copilot = SnowShieldCortexCopilot(use_mock_if_no_creds=False)
    
    if args.command == "list-skills":
        print(f"{BOLD}Registered Snowflake CoCo Skills:{RESET}")
        print(f"  1. {CYAN}{BOLD}risk-audit-skill{RESET}          - Analyzes telemetry, exfiltration risks, and Cortex threat scoring.")
        print(f"  2. {CYAN}{BOLD}compliance-guard-skill{RESET}    - Validates GDPR, PCI-DSS 4.0, and SOC 2; generates DDM policies.")
        print(f"  3. {CYAN}{BOLD}auto-remediation-skill{RESET}    - AST code vulnerability patching, git diff & GitHub PR generation.\n")
        return

    if args.command == "run":
        if args.skill == "risk-audit-skill":
            run_risk_audit_skill(args.prompt, copilot)
        elif args.skill == "compliance-guard-skill":
            run_compliance_guard_skill(args.prompt, copilot)
        elif args.skill == "auto-remediation-skill":
            run_auto_remediation_skill(args.prompt, copilot)
    else:
        parser.print_help()

if __name__ == "__main__":
    main()
